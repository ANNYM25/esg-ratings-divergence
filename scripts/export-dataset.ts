/**
 * Export the dataset and the TypeScript engine's reference results for the
 * Python research package (python/esg_divergence).
 *
 *   npm run export:data
 *
 * Writes:
 *   data/companies.json   company universe + attributes
 *   data/ratings.json     raw provider ratings with provenance
 *   data/providers.json   provider scales and methodology profiles
 *   data/ratings.csv      tidy long-format table for pandas / Excel users
 *   data/reference.json   every headline figure as computed by src/lib — the
 *                         Python port's test suite must reproduce it exactly
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { COMPANIES, SECTORS } from "../src/data/companies";
import { RATINGS } from "../src/data/ratings";
import { correlationMatrix, sectorDivergence, universe, universeStats } from "../src/lib/divergence";
import { normalisedRatingsFor } from "../src/lib/normalise";
import { predictorSummary } from "../src/lib/predictors";
import { PROVIDERS } from "../src/lib/providers";
import { analyseAllScreens, screeningHeadline, turnoverAcrossScreens } from "../src/lib/screening";
import { inferenceSummary } from "../src/lib/statistics";

const OUT = join(__dirname, "..", "data");
mkdirSync(OUT, { recursive: true });

const write = (name: string, value: unknown) => {
  writeFileSync(join(OUT, name), JSON.stringify(value, null, 2) + "\n");
  console.log(`  data/${name}`);
};

write("companies.json", { sectors: SECTORS, companies: COMPANIES });
write("ratings.json", RATINGS);
write("providers.json", PROVIDERS);

const header = ["ticker", "name", "sector", "provider", "raw_score", "raw_label", "normalised",
  "band_low", "band_high", "sector_percentile", "universe_percentile", "provenance", "as_of"];
const rows = COMPANIES.flatMap((c) =>
  normalisedRatingsFor(c.ticker).map((r) =>
    [c.ticker, `"${c.name}"`, c.sector, r.provider, r.raw, `"${r.rawLabel ?? ""}"`, r.normalised,
      r.band.low, r.band.high, r.sectorPercentile, r.universePercentile, r.provenance, r.asOf].join(","),
  ),
);
writeFileSync(join(OUT, "ratings.csv"), [header.join(","), ...rows].join("\n") + "\n");
console.log("  data/ratings.csv");

const inference = inferenceSummary();
const predictors = predictorSummary();
write("reference.json", {
  _note: "Generated by scripts/export-dataset.ts from the TypeScript engine. Do not edit by hand.",
  universe: universe().map((r) => ({
    ticker: r.ticker, sector: r.sector, consensus: r.consensus,
    score: r.divergence.score, band: r.divergence.band, profile: r.divergence.profile,
    normalisedRange: r.divergence.normalisedRange, percentileRange: r.divergence.percentileRange,
    stdDev: r.divergence.stdDev, pillarRanges: r.divergence.pillarRanges,
  })),
  universeStats: (({ mostDivergent, ...rest }) => ({ ...rest, mostDivergent: mostDivergent.ticker }))(universeStats()),
  sectorDivergence: sectorDivergence(),
  correlationMatrix: correlationMatrix(),
  inference,
  screens: analyseAllScreens().map((s) => ({
    id: s.screen.id, contestedCount: s.contestedCount, contestedShare: s.contestedShare,
    portfolioSizeByProvider: s.portfolioSizeByProvider, unanimousInclude: s.unanimousInclude,
    unanimousExclude: s.unanimousExclude, minOverlap: s.minOverlap,
    contested: s.contested.map((c) => c.ticker),
  })),
  screeningHeadline: (({ worst, best, ...rest }) => ({ ...rest, worst: worst.screen.id, best: best.screen.id }))(
    screeningHeadline(),
  ),
  turnover: turnoverAcrossScreens().map(({ screen, ...rest }) => ({ screen: screen.id, ...rest })),
  predictors: {
    supported: predictors.supported,
    strongest: predictors.strongest.id,
    results: predictors.results.map((r) => ({
      id: r.id, spread: r.spread, effectSize: r.effectSize, effectLabel: r.effectLabel,
      separated: r.separated, supported: r.supported, comparedGroups: r.comparedGroups,
      groups: r.groups.map((g) => ({ label: g.label, n: g.n, meanDivergence: g.meanDivergence })),
    })),
  },
});
